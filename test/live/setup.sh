#!/usr/bin/env bash
# Prepares GCP for a live integration run. Records everything it changes in
# test/live/.state/env so teardown.sh can undo it.
#
# Usage:
#   test/live/setup.sh --mode single --project-a PROJECT_A --model MODEL
#   test/live/setup.sh --mode dual   --project-a PROJECT_A --project-b PROJECT_B --model MODEL
#
# Env overrides: GQG_REGION_PRIMARY (us-central1), GQG_REGION_FALLBACK (europe-west1),
#                GQG_LOWERED_RPM (10), DRY_RUN=1 (print mutating commands only)

source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

MODE="" PROJECT_A="" PROJECT_B="" MODEL=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --mode)      MODE="$2"; shift 2 ;;
    --project-a) PROJECT_A="$2"; shift 2 ;;
    --project-b) PROJECT_B="$2"; shift 2 ;;
    --model)     MODEL="$2"; shift 2 ;;
    -h|--help)   sed -n '2,12p' "$0"; exit 0 ;;
    *)           die "unknown argument: $1" ;;
  esac
done

[[ "${MODE}" == "single" || "${MODE}" == "dual" ]] || die "--mode must be 'single' or 'dual'"
[[ -n "${PROJECT_A}" ]] || die "--project-a is required"
[[ -n "${MODEL}" ]] || die "--model is required (base model ID, e.g. gemini-2.5-flash)"
if [[ "${MODE}" == "dual" ]]; then
  [[ -n "${PROJECT_B}" ]] || die "--project-b is required in dual mode"
  [[ "${PROJECT_B}" != "${PROJECT_A}" ]] || die "--project-b must differ from --project-a"
else
  PROJECT_B=""
fi
[[ ! -f "${STATE_FILE}" ]] || die "a previous run was not torn down (${STATE_FILE} exists). Run test/live/teardown.sh first."

require_tools
require_adc
require_free_ports

PROJECTS=("${PROJECT_A}")
[[ -n "${PROJECT_B}" ]] && PROJECTS+=("${PROJECT_B}")

# --- Organization -----------------------------------------------------------
if [[ "${DRY_RUN}" == "1" ]]; then
  ORG_ID="${GQG_ORG_ID:-000000000000}"
else
  ORG_ID="$(org_of "${PROJECT_A}")"
  [[ -n "${ORG_ID}" ]] || die "could not determine the organization of ${PROJECT_A}"
  if [[ -n "${PROJECT_B}" ]]; then
    ORG_B="$(org_of "${PROJECT_B}")"
    [[ "${ORG_B}" == "${ORG_ID}" ]] || die "${PROJECT_A} (org ${ORG_ID}) and ${PROJECT_B} (org ${ORG_B}) must be in the same organization"
  fi
fi
log "mode=${MODE} org=${ORG_ID} projects=${PROJECTS[*]} model=${MODEL}"

mkdir -p "${STATE_DIR}"
: > "${STATE_FILE}"
save_state MODE "${MODE}"
save_state PROJECT_A "${PROJECT_A}"
save_state PROJECT_B "${PROJECT_B}"
save_state MODEL "${MODEL}"
save_state ORG_ID "${ORG_ID}"
save_state REGION_PRIMARY "${GQG_REGION_PRIMARY}"
save_state REGION_FALLBACK "${GQG_REGION_FALLBACK}"

# --- APIs -------------------------------------------------------------------
# Only APIs that were disabled before the run are recorded, so teardown never
# disables something another workload depends on.
for project in "${PROJECTS[@]}"; do
  if [[ "${DRY_RUN}" == "1" ]]; then
    enabled=""
  else
    # Must succeed: guessing wrong here would make teardown disable APIs that
    # were already enabled before the test.
    enabled="$(gcloud services list --enabled --project="${project}" --format='value(config.name)')" \
      || die "cannot list enabled APIs on ${project} (need serviceusage.services.list)"
  fi
  for api in "${REQUIRED_APIS[@]}"; do
    if ! grep -qx "${api}" <<<"${enabled}"; then
      log "enabling ${api} on ${project}"
      run gcloud services enable "${api}" --project="${project}"
      save_state "ENABLED_API_${project//-/_}_${api//[.-]/_}" "${project} ${api}"
    fi
  done
done

# --- Lower the primary RPM quota on project A -------------------------------
if [[ "${DRY_RUN}" == "1" ]]; then
  ORIGINAL_RPM="${GQG_ORIGINAL_RPM:-1000}"
else
  ORIGINAL_RPM="$(current_rpm_limit "${PROJECT_A}" "${GQG_REGION_PRIMARY}" "${MODEL}")"
fi
if [[ -z "${ORIGINAL_RPM}" ]]; then
  die "no '${RPM_QUOTA_ID}' entry for region=${GQG_REGION_PRIMARY}, base_model=${MODEL} in ${PROJECT_A}.
       The model may use Dynamic Shared Quota (no per-project limit) or the model ID is not a base model ID.
       List available entries with:
         gcloud beta quotas info describe ${RPM_QUOTA_ID} --service=${QUOTA_SERVICE} --project=${PROJECT_A} --format=json | jq '.dimensionsInfos[].dimensions'"
fi
(( ORIGINAL_RPM == -1 || ORIGINAL_RPM > GQG_LOWERED_RPM )) \
  || die "current limit (${ORIGINAL_RPM}) is already <= GQG_LOWERED_RPM (${GQG_LOWERED_RPM}); pick a lower value"

# Record before mutating so teardown can always restore.
save_state ORIGINAL_RPM "${ORIGINAL_RPM}"
save_state LOWERED_RPM "${GQG_LOWERED_RPM}"
save_state PREFERENCE_SET 1
log "lowering ${PROJECT_A} ${GQG_REGION_PRIMARY}/${MODEL} RPM: ${ORIGINAL_RPM} -> ${GQG_LOWERED_RPM}"
set_rpm_preference "${PROJECT_A}" "${GQG_REGION_PRIMARY}" "${MODEL}" "${GQG_LOWERED_RPM}"

# --- Governor config for the test ------------------------------------------
{
  echo "# Generated by test/live/setup.sh; removed by teardown.sh"
  echo "org_id: \"${ORG_ID}\""
  echo "project_ids:"
  for project in "${PROJECTS[@]}"; do echo "  - \"${project}\""; done
  echo "regions: [\"${GQG_REGION_PRIMARY}\", \"${GQG_REGION_FALLBACK}\"]"
  echo "models: [\"${MODEL}\"]"
  echo "poll_interval: 15s"
  echo "poll_timeout: 10s"
  echo "safety_margin: 10"
  echo "custom_policies:"
  echo "  fallback:"
  echo "    cascade:"
  echo "      - target_model: \"${MODEL}\""
  echo "        region: \"${GQG_REGION_FALLBACK}\""
} > "${STATE_DIR}/governor.yaml"
save_state CONFIG "${STATE_DIR}/governor.yaml"

log "setup complete. State: ${STATE_FILE}"
log "quota preference changes can take a few minutes to apply; the test waits for them."
